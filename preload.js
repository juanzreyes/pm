  saveCalendar: (url) => ipcRenderer.invoke('cal:save', url),
  removeCalendar: () => ipcRenderer.invoke('cal:remove'),
  refreshCalendar: () => ipcRenderer.invoke('cal:refresh'),
  join: (url) => ipcRenderer.send('join', url),
  pomoStart: () => ipcRenderer.send('pomo:start'),
  pomoStop: () => ipcRenderer.send('pomo:stop'),
  addReminder: (text) => ipcRenderer.invoke('reminder:add', text),
  removeReminder: (id) => ipcRenderer.send('reminder:remove', id),
  gitYesterday: () => ipcRenderer.invoke('git:yesterday'),
