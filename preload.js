  copy: (text) => ipcRenderer.invoke('copy', text),
  exportTimesheet: () => ipcRenderer.invoke('timesheet:export'),
  updateIntegrations: (patch) => ipcRenderer.invoke('settings:integrations', patch),
  setAiKey: (k) => ipcRenderer.invoke('ai:setKey', k),
  aiPolish: (text, kind) => ipcRenderer.invoke('ai:polish', { text, kind }),
  onThinking: on('chat:thinking'),
  shopBuy: (id) => ipcRenderer.invoke('shop:buy', id),
  shopEquip: (id) => ipcRenderer.invoke('shop:equip', id),
  shopUnequip: (slot) => ipcRenderer.invoke('shop:unequip', slot),
  stats: () => ipcRenderer.invoke('stats:get'),
  addMonitor: (url, name) => ipcRenderer.invoke('monitor:add', { url, name }),
